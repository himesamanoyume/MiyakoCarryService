        /// <summary>
        /// 模组知识库（完整版）。内容取自 README.md / Forge.md / Oddba.html 的功能介绍与教程，
        /// 用于回答玩家对 Client 指令、机制、配置与操作方式的疑问。
        /// </summary>
        private const string KnowledgeBase = """
            KNOWLEDGE BASE — features, mechanics and tutorials of this mod. Answer player questions about them using this information:

            OVERVIEW:
            - Mcs mimics a real "carry service": the 老板 selects a service, places an 订单 (order), pays, and plays together with the 护航 who come to serve.
            - Ordering: "mcs order {player count 1-4} {spawn type index} {carry-service level (护航级别) 1-5} {duration in hours}". You (Miyako) issue a payment quest; once paid, the 护航 are added as friends and can be invited into the raid group.
            - The mod supports loot scavenging by rules, a formation system, full equipment customization (Mcs Inventory Mode), proxy actions, Fika multiplayer (each player has their own squad), and custom 护航 types.

            COMMANDS (issued through the in-game action menu or by voice):
            - Individual commands target one 护航; team commands (全队...) target the whole squad. Unless stated otherwise, movement/action commands only take effect when the 护航 is not in combat.
              - Report Enemy Position (报告敌人方位): report known enemy positions (only while in combat).
              - Report Self Status (报告自身状态): report own health and supply status.
              - On Your Own (自主行动): act independently.
              - Regroup (集结): stop all actions and regroup at the 老板.
              - Follow Me (跟随我): follow the 老板; while following, 护航 do not attack enemies or loot.
              - Exclude / Take Over (排除/接管): Exclude stops a 护航 from receiving team commands; Take Over restores team command control.
              - Go To (前往): go to a specified location.
              - Hold Position (驻守): stay in place.
              - Escort (护送): escort to a specified location — quest location (任务地点), exfil (撤离点), transit point (转移点), switch (开关), stationary weapon (固定武器), BTR, airdrop (空投).
              - Force Teleport (强制传送): clear aggro and attempt to teleport to the 老板's current position.
              - Open Inventory (打开背包): remotely open a 护航's backpack to transfer loot it picked up (unavailable when BalanceRestriction is enabled).
              - Change Aiming Body Part (改变瞄准部位): change the preferred combat aiming body part.
              - Proxy Action (代理行动): the 护航 acts alone at a location — complete supported quest conditions, operate a switch, open a locked door, pick up loot, or operate a stationary weapon.
              - Drop Target Loot (丢出目标战利品): drop the target loot picked up during the raid.
              - Clear Area (清扫区域): clear the surrounding area of a specified location.
              - Change Formation (改变队形): immediately apply a saved formation preset.
            - The command system also works in Fika multiplayer when the MiyakoCarryServiceFika addon is installed.

            MECHANICS:
            - Loot rules: loot below the Price Threshold is ignored; keyword loot matches item full/short names (keywords separated by "||" or "," or "，"); blocked item types can be selected (Ammo, Barter, Info, Container, Food, Backpack, Goggles, Pocket, Tactical Vest, Armor, Grenade, Headphone, Keys, Knife, Magazine, Meds, Mod, Special, Weapon, Other); looted items are nested as much as possible. Loot picked up by 护航 must be taken personally by the 老板 to keep it after the raid.
